"""Build responsive WebP assets from retained originals; never changes product artwork."""
import hashlib,json
from pathlib import Path
from PIL import Image
root=Path(__file__).resolve().parents[1]
manifest={}
for source in sorted((root/'public/images').glob('*.webp'))+sorted((root/'public/images/drop-002').glob('*.webp')):
    original=Image.open(source)
    digest=hashlib.sha256(source.read_bytes()).hexdigest()[:8]
    variants=[]
    for width in [320,600,1000]:
        if width>original.width:continue
        image=original.copy();image.thumbnail((width,10000),Image.Resampling.LANCZOS)
        target=root/'public/images/optimized'/f'{source.stem}-{width}-{digest}.webp'
        image.save(target,'WEBP',quality=83,method=6)
        variants.append({'src':'/'+str(target.relative_to(root/'public')),'width':image.width})
    manifest['/'+str(source.relative_to(root/'public'))]=variants
logo=Image.open(root/'public/brand/treau-logo.png')
digest=hashlib.sha256((root/'public/brand/treau-logo.png').read_bytes()).hexdigest()[:8]
for size in [160,320,640]:
    image=logo.copy();image.thumbnail((size,size),Image.Resampling.LANCZOS)
    image.save(root/f'public/brand/treau-mark-{size}-{digest}.webp','WEBP',quality=88,method=6)
icon=logo.copy();icon.thumbnail((64,64),Image.Resampling.LANCZOS);icon.save(root/'public/brand/treau-icon.png',optimize=True)
(root/'lib/responsive-images.ts').write_text('/* Generated by scripts/optimize-images.py from retained source images. */\nexport const responsiveImages:Record<string,{src:string;width:number}[]>='+json.dumps(manifest,separators=(',',':'))+';\nexport const brandMark={small:"/brand/treau-mark-160-'+digest+'.webp",medium:"/brand/treau-mark-320-'+digest+'.webp",large:"/brand/treau-mark-640-'+digest+'.webp"};\n')
print('Responsive images:',len(manifest),'Logo hash:',digest)
